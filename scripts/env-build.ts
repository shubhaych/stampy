/** npm run env:build — generate .env.example from env/<feature>.env fragments (names and safe defaults only). */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT } from './lib';

const ORDER = ['ops', 'web-core', 'seats', 'policy', 'voice-engine', 'planner', 'qc-data'];
const dir = join(ROOT, 'env');
const files = readdirSync(dir).filter((f) => f.endsWith('.env')).map((f) => f.replace(/\.env$/, ''));
files.sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b));

const SECRET = /(KEY|TOKEN|SECRET|SID)$/;
const seen = new Map<string, string>();
const parts = ['# GENERATED by `npm run env:build` from env/*.env. Do not edit; edit your feature fragment.', '# Copy to .env.local (git-ignored). Secrets stay empty here and never go in web/.', ''];
for (const f of files) {
  const text = readFileSync(join(dir, `${f}.env`), 'utf8').trimEnd();
  for (const line of text.split('\n')) {
    const m = line.match(/^([A-Z0-9_]+)=([^#]*)/);
    if (!m) continue;
    if (seen.has(m[1]!)) throw new Error(`${m[1]} defined in env/${seen.get(m[1]!)}.env and env/${f}.env`);
    seen.set(m[1]!, f);
    if (SECRET.test(m[1]!) && m[2]!.trim()) throw new Error(`env/${f}.env sets a value for secret ${m[1]}; fragments carry names only`);
  }
  parts.push(`# ===== env/${f}.env =====`, text, '');
}
writeFileSync(join(ROOT, '.env.example'), parts.join('\n'));
console.log(`env:build: .env.example from ${files.length} fragments, ${seen.size} variables`);
